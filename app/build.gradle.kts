        if (!keystoreFile.isNullOrBlank()) {
            create("release") {
                storeFile = file(keystoreFile)
                storePassword = System.getenv("MRPYTHON_KEYSTORE_PASSWORD")
                keyAlias = System.getenv("MRPYTHON_KEY_ALIAS")
                keyPassword = System.getenv("MRPYTHON_KEY_PASSWORD")
            }
        }
    }

